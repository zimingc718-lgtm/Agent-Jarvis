def append_ledger_event(root: Path, payload: dict[str, object]) -> list[str]:
    ledger_path = root / LEDGER_PATH
    ledger_path.parent.mkdir(parents=True, exist_ok=True)

    existing_findings = check_ledger(root)
    if existing_findings:
        return existing_findings

    events = read_ledger_events(ledger_path)
    previous_hash = events[-1]["hash"] if events else "GENESIS"
    event = {
        "seq": len(events) + 1,
        "timestamp": now_utc(),
        "prev_hash": previous_hash,
        **payload,
    }
    event["hash"] = sha256_text(canonical_json(event))

    with ledger_path.open("a", encoding="utf-8", newline="\n") as handle:
        handle.write(canonical_json(event) + "\n")
    return []


def read_ledger_events(path: Path) -> list[dict[str, object]]:
    if not path.exists():
        return []
    events = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            events.append(json.loads(line))
    return events


