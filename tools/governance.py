def check_g3(root: Path) -> list[str]:
    required_tests = extract_ids(read_text(root / "project/04_tests/测试说明书.md"), "TEST")
    evidence = load_test_results(root)
    if isinstance(evidence, str):
        return [evidence]

    results = {item.get("id"): item for item in evidence}
    missing = sorted(test_id for test_id in required_tests if test_id not in results)

    def is_manual(item: dict[str, object]) -> bool:
        return str(item.get("verification", "")).lower() == "manual"

    def is_deferred(item: dict[str, object]) -> bool:
        # A test bound only to a requirement that has been formally deferred
        # (its "blocks" requirement is DEFERRED in the spec). It is not evidence
        # of a shipped behaviour, so it neither passes nor blocks — it is skipped
        # and reported, and returns with the deferring CR.
        return str(item.get("result", "")).upper() == "DEFERRED"

    pending_manual: list[str] = []
    unattributed_manual: list[str] = []
    deferred: list[str] = []
    failed: list[str] = []

    for test_id in sorted(required_tests):
        item = results.get(test_id)
        if item is None:
            continue
        passed = str(item.get("result", "")).upper() == "PASS"
        if is_deferred(item):
            deferred.append(test_id)
        elif is_manual(item):
            # A manual item cannot be satisfied by a bare "PASS": it must name
            # who verified it and when, so it stays auditable and cannot be
            # silently flipped to green.
            if not passed:
                pending_manual.append(test_id)
            elif not (str(item.get("verified_by", "")).strip() and str(item.get("verified_at", "")).strip()):
                unattributed_manual.append(test_id)
        elif not passed:
            failed.append(test_id)

    findings: list[str] = []
    if missing:
        findings.append(f"FAIL G3_BLOCKED missing PASS evidence for: {', '.join(missing)}")
    if failed:
        findings.append(f"FAIL G3_BLOCKED failing test evidence for: {', '.join(failed)}")
    if pending_manual:
        findings.append(
            "FAIL G3_BLOCKED manual verification pending (a human must run it and record "
            f"verified_by/verified_at): {', '.join(pending_manual)}"
        )
    if unattributed_manual:
        findings.append(
            "FAIL G3_BLOCKED manual verification marked PASS without verified_by/verified_at: "
            f"{', '.join(unattributed_manual)}"
        )
    if findings:
        return findings
    if deferred:
        return [
            "OK G3_PASS all non-deferred required tests have current PASS evidence "
            f"(deferred, tracked by their CR: {', '.join(deferred)})"
        ]
    return ["OK G3_PASS all required tests have current PASS evidence"]


def check_g35(root: Path) -> list[str]:
    evidence = load_test_results(root)
    if isinstance(evidence, str):
        return [evidence.replace("G3_BLOCKED", "G3_5_BLOCKED")]

    for item in evidence:
        if str(item.get("result", "")).upper() == "PASS" and item.get("real_entry") is True:
            return ["OK G3_5_PASS real-entry smoke evidence is present"]
    return ["FAIL G3_5_BLOCKED no real-entry smoke PASS evidence has been registered"]


def load_test_results(root: Path) -> list[dict[str, object]] | str:
    path = root / TEST_RESULTS_PATH
    if not path.exists():
        return f"FAIL G3_BLOCKED missing {to_posix(TEST_RESULTS_PATH)}"
    try:
      data = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
      return f"FAIL G3_BLOCKED invalid {to_posix(TEST_RESULTS_PATH)} JSON: {exc}"
    tests = data.get("tests")
    if not isinstance(tests, list):
        return f"FAIL G3_BLOCKED {to_posix(TEST_RESULTS_PATH)} must contain a tests array"
    return [item for item in tests if isinstance(item, dict)]


def check_changes(root: Path) -> list[str]:
    changes_dir = root / "project/06_changes"
    if not changes_dir.is_dir():
        return ["FAIL MISSING_REQUIRED_DIR project/06_changes"]

    records = sorted(path for path in changes_dir.glob("CR-*.md") if path.is_file())
    findings: list[str] = []
    for record in records:
        text = read_text(record)
        missing = [label for label in CHANGE_REQUIRED_LABELS if f"{label}：" not in text and f"{label}:" not in text]
        if missing:
            rel_path = to_posix(record.relative_to(root))
            findings.append(f"FAIL CHANGE_RECORD_INCOMPLETE {rel_path} missing: {', '.join(missing)}")

    if findings:
        return findings
    if not records:
        return ["OK CHANGE_RECORDS_PASS no change records to validate"]
    return [f"OK CHANGE_RECORDS_PASS validated {len(records)} change record(s)"]


def check_ui_process_control(root: Path) -> list[str]:
    findings: list[str] = []

    ui_standard_path = root / UI_STANDARD_PATH
    if not ui_standard_path.is_file():
        return [f"FAIL MISSING_REQUIRED_FILE {to_posix(UI_STANDARD_PATH)}"]

    standard_text = read_text(ui_standard_path)
    missing_markers = [marker for marker in UI_REQUIRED_MARKERS if marker not in standard_text]
    if missing_markers:
        findings.append(
            "FAIL UI_STANDARD_INCOMPLETE "
            f"{to_posix(UI_STANDARD_PATH)} missing: {', '.join(missing_markers)}"
        )

    package_path = root / "package.json"
    if not package_path.is_file():
        findings.append("FAIL UI_PACKAGE_MISSING package.json")
    else:
        try:
            package_data = json.loads(package_path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            findings.append(f"FAIL UI_PACKAGE_INVALID_JSON package.json {exc}")
        else:
            scripts = package_data.get("scripts")
            if not isinstance(scripts, dict):
                findings.append("FAIL UI_SCRIPTS_MISSING package.json scripts")
            else:
                for script_name in UI_REQUIRED_SCRIPTS:
                    script_value = scripts.get(script_name)
                    if not isinstance(script_value, str) or not script_value.strip():
                        findings.append(f"FAIL UI_SCRIPT_MISSING {script_name}")

    if project_has_ui_source(root):
        if not (root / UI_CONTRACT_SCRIPT_PATH).is_file():
            findings.append(f"FAIL UI_CONTRACT_SCRIPT_MISSING {to_posix(UI_CONTRACT_SCRIPT_PATH)}")
        if not any((root / "tests").glob("**/*.test.tsx")):
            findings.append("FAIL UI_COMPONENT_TEST_MISSING tests/**/*.test.tsx")
        if not any((root / "tests/e2e").glob("*.spec.ts")) and not any((root / "tests/e2e").glob("*.spec.tsx")):
            findings.append("FAIL UI_REAL_ENTRY_TEST_MISSING tests/e2e/*.spec.ts")

    if findings:
        return findings
    return ["OK UI_CONTROL_PASS UI standards, scripts, and interaction coverage controls are present"]


def project_has_ui_source(root: Path) -> bool:
    src_path = root / "src"
    if not src_path.is_dir():
        return False
    return any(src_path.glob("**/*.tsx"))


def append_ledger_event(root: Path, payload: dict[str, object]) -> list[str]:
    ledger_path = root / LEDGER_PATH
    ledger_path.parent.mkdir(parents=True, exist_ok=True)

    existing_findings = check_ledger(root)
    if existing_findings:
        return existing_findings

    events = read_ledger_events(ledger_path)
    previous_hash = events[-1]["hash"] if events else "GENESIS"
    event = {
        "seq": len(events) + 1,
        "timestamp": now_utc(),
        "prev_hash": previous_hash,
        **payload,
    }
    event["hash"] = sha256_text(canonical_json(event))

    with ledger_path.open("a", encoding="utf-8", newline="\n") as handle:
        handle.write(canonical_json(event) + "\n")
    return []


def read_ledger_events(path: Path) -> list[dict[str, object]]:
    if not path.exists():
        return []
    events = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            events.append(json.loads(line))
    return events


def meaningful_input_exists(text: str) -> bool:
    if "尚未建立" in text or "等待用户确认" in text:
        return False
    normalized = re.sub(r"[\s#`|：:。.,，-]", "", text)
    return len(normalized) >= 20


def contains_placeholder_state(text: str) -> bool:
    return any(marker in text for marker in PLACEHOLDER_MARKERS)


def approved_status_exists(text: str) -> bool:
    return bool(re.search(r"当前状态\s*[：:]\s*APPROVED", text, re.IGNORECASE))


def approved_requirement_row_exists(text: str) -> bool:
    for line in text.splitlines():
        if not line.strip().startswith("|"):
            continue
        if "REQ-" not in line:
            continue
        cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
        if len(cells) < 6:
            continue
        has_priority = cells[2] in {"MUST", "SHOULD", "COULD"}
        has_acceptance = bool(cells[4])
        is_approved = cells[-1].upper() == "APPROVED"
        if has_priority and has_acceptance and is_approved:
            return True
    return False


def extract_ids(text: str, prefix: str) -> set[str]:
    return set(re.findall(rf"\b{re.escape(prefix)}-[A-Z0-9-]+\b", text))


def is_ok(messages: Iterable[str]) -> bool:
    return all(message.startswith("OK ") for message in messages)


def read_text(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def canonical_json(value: object) -> str:
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))


def now_utc() -> str:
    return dt.datetime.now(dt.UTC).replace(microsecond=0).isoformat()


def to_posix(path: Path) -> str:
    return path.as_posix()


def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    code, output = run()
    sys.stdout.write(output)
    return code


if __name__ == "__main__":
    raise SystemExit(main())
