def verify(root: Path) -> list[str]:
    findings: list[str] = []
    findings.extend(check_required_structure(root))
    findings.extend(m for m in check_ui_process_control(root) if not m.startswith("OK "))
    findings.extend(check_baseline(root))
    findings.extend(check_ledger(root))

    if findings:
        return findings
    return ["OK VERIFY_PASS governance files and integrity checks passed"]


def gate(root: Path, gate_name: str, cr: str | None = None) -> list[str]:
    structure_findings = check_required_structure(root)
    if structure_findings:
        return structure_findings

    if gate_name == "g1":
        return check_g1(root)
    if gate_name == "g2":
        g1 = check_g1(root)
        if not is_ok(g1):
            return ["FAIL G2_BLOCKED G1 must pass before G2"] + g1
        return check_g2(root)
    if gate_name == "g3":
        g2 = gate(root, "g2")
        if not is_ok(g2):
            return ["FAIL G3_BLOCKED G2 must pass before implementation validation"] + g2
        return check_g3(root, cr=cr)
    if gate_name == "g3.5":
        g3 = gate(root, "g3", cr=cr)
        if not is_ok(g3):
            return ["FAIL G3_5_BLOCKED G3 must pass before real-entry smoke validation"] + g3
        return check_g35(root, cr=cr)
    if gate_name == "g4":
        # A release is judged at full scope by definition: a narrowing view must
        # never be able to relax it (CR-20260910-process-hardening CP-5).
        if cr:
            return ["FAIL G4_BLOCKED release must be judged at full scope; --cr is not accepted"]
        lower = gate(root, "g3.5")
        if not is_ok(lower):
            return ["FAIL G4_BLOCKED G3.5 must pass before release"] + lower
        return check_g4(root)
    return [f"FAIL UNKNOWN_GATE unsupported gate: {gate_name}"]


def snapshot(root: Path, actor: str) -> list[str]:
    findings = check_required_structure(root)
    if findings:
        return findings

    baseline = {
        "schema_version": 1,
        "created_at": now_utc(),
        "files": {rel_path: governed_hash(root / rel_path, rel_path) for rel_path in discover_controlled_files(root)},
    }
    baseline_json = canonical_json(baseline)
    baseline["baseline_sha256"] = sha256_text(baseline_json)

    baseline_path = root / BASELINE_PATH
    baseline_path.parent.mkdir(parents=True, exist_ok=True)
    baseline_path.write_text(canonical_json(baseline) + "\n", encoding="utf-8")

    ledger_findings = append_ledger_event(
        root,
        {
            "action": "snapshot",
            "actor": actor,
            "payload_sha256": baseline["baseline_sha256"],
            "files": baseline["files"],
        },
    )
    if ledger_findings:
        return ledger_findings

    return [f"OK SNAPSHOT_WRITTEN {to_posix(BASELINE_PATH)}"]


def check_required_structure(root: Path) -> list[str]:
    findings: list[str] = []
    for rel_dir in PROJECT_DIRS:
        if not (root / rel_dir).is_dir():
            findings.append(f"FAIL MISSING_REQUIRED_DIR {rel_dir}")
    for rel_path in REQUIRED_FILES:
        if not (root / rel_path).is_file():
            findings.append(f"FAIL MISSING_REQUIRED_FILE {rel_path}")
    return findings


def check_baseline(root: Path) -> list[str]:
    baseline_path = root / BASELINE_PATH
    if not baseline_path.exists():
        return []

    try:
        baseline = json.loads(baseline_path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        return [f"FAIL BASELINE_INVALID_JSON {to_posix(BASELINE_PATH)} {exc}"]

    findings: list[str] = []
    files = baseline.get("files")
    if not isinstance(files, dict):
        return [f"FAIL BASELINE_INVALID_SCHEMA {to_posix(BASELINE_PATH)} missing files object"]

    for rel_path, expected_hash in files.items():
        path = root / rel_path
        if not path.exists():
            findings.append(f"FAIL BASELINE_FILE_MISSING {rel_path}")
            continue
        actual_hash = governed_hash(path, rel_path)
        if actual_hash != expected_hash:
            findings.append(f"FAIL BASELINE_CHANGED {rel_path}")

    current_files = set(discover_controlled_files(root))
    baseline_files = set(files)
    for rel_path in sorted(current_files - baseline_files):
        findings.append(f"FAIL UNBASELINED_FILE {rel_path}")
    return findings


def discover_controlled_files(root: Path) -> list[str]:
    files: list[str] = []
    for path in root.rglob("*"):
        if not path.is_file():
            continue
        rel_path = path.relative_to(root)
        rel_parts = rel_path.parts
        if any(part in IGNORED_DIR_NAMES for part in rel_parts[:-1]):
            continue
        if any(part.startswith(IGNORED_DIR_PREFIXES) for part in rel_parts[:-1]):
            continue
        if rel_path.parts[:2] == ("project", ".governance"):
            continue
        if path.name in IGNORED_FILE_NAMES:
            continue
        if any(path.name.endswith(suffix) for suffix in IGNORED_SUFFIXES):
            continue
        files.append(to_posix(rel_path))
    return sorted(files)


def check_ledger(root: Path) -> list[str]:
    ledger_path = root / LEDGER_PATH
    if not ledger_path.exists():
        return []

    findings: list[str] = []
    previous_hash = "GENESIS"
    expected_seq = 1
    for line_number, line in enumerate(ledger_path.read_text(encoding="utf-8").splitlines(), start=1):
        if not line.strip():
            continue
        try:
            event = json.loads(line)
        except json.JSONDecodeError as exc:
            findings.append(f"FAIL LEDGER_INVALID_JSON line={line_number} {exc}")
            continue

        if event.get("seq") != expected_seq:
            findings.append(f"FAIL LEDGER_BAD_SEQUENCE line={line_number}")
        if event.get("prev_hash") != previous_hash:
            findings.append(f"FAIL LEDGER_BROKEN_CHAIN line={line_number}")

        recorded_hash = event.get("hash")
        event_without_hash = dict(event)
        event_without_hash.pop("hash", None)
        actual_hash = sha256_text(canonical_json(event_without_hash))
        if recorded_hash != actual_hash:
            findings.append(f"FAIL LEDGER_HASH_MISMATCH line={line_number}")

        previous_hash = str(recorded_hash)
        expected_seq += 1

    return findings


