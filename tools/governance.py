CHANGE_RESPONSE_PREFIX = "变更响应 · "

# Review content belongs to the change record, never to a spec (CP-2).
REVIEW_HEADING_PATTERNS = [
    re.compile(r"多角色评审"),
    re.compile(r"复盘迭代"),
    re.compile(r"评审（R[1-4]"),
    re.compile(r"R[1-4] 四角色审查"),
    re.compile(r"^CR-\S+\s*评审"),
]


def check_specs(root: Path) -> list[str]:
    """Machine-check the spec structure contract (CP-12, DEC-020 (1))."""
    findings: list[str] = []
    for rel_path, allowed in SPEC_BASELINE_SECTIONS.items():
        path = root / rel_path
        if not path.exists():
            findings.append(f"FAIL SPECS_MISSING {rel_path}")
            continue
        seen: dict[str, int] = {}
        for line in read_text(path).splitlines():
            match = re.match(r"^(#{2,3})\s+(.*?)\s*$", line)
            if not match:
                continue
            level, title = len(match.group(1)), match.group(2)
            if any(pattern.search(title) for pattern in REVIEW_HEADING_PATTERNS):
                findings.append(
                    f"FAIL SPECS_REVIEW_IN_SPEC {rel_path}: review sections belong to the CR - '{title}'"
                )
                continue
            if level != 2:
                continue
            if title.startswith(CHANGE_RESPONSE_PREFIX):
                cr = title[len(CHANGE_RESPONSE_PREFIX):].strip()
                seen[cr] = seen.get(cr, 0) + 1
                continue
            if title not in allowed:
                findings.append(
                    f"FAIL SPECS_UNKNOWN_SECTION {rel_path}: '{title}' is neither a baseline section "
                    f"nor a '{CHANGE_RESPONSE_PREFIX}<CR>' section"
                )
        for cr, count in seen.items():
            if count > 1:
                findings.append(
                    f"FAIL SPECS_DUPLICATE_RESPONSE {rel_path}: {cr} has {count} change-response sections (expected 1)"
                )
    if findings:
        return findings
    return [f"OK SPECS_PASS {len(SPEC_BASELINE_SECTIONS)} spec(s) match the structure contract"]


def check_ui_process_control(root: Path) -> list[str]:
    findings: list[str] = []

    ui_standard_path = root / UI_STANDARD_PATH
    if not ui_standard_path.is_file():
        return [f"FAIL MISSING_REQUIRED_FILE {to_posix(UI_STANDARD_PATH)}"]

    standard_text = read_text(ui_standard_path)
    missing_markers = [marker for marker in UI_REQUIRED_MARKERS if marker not in standard_text]
    if missing_markers:
        findings.append(
            "FAIL UI_STANDARD_INCOMPLETE "
            f"{to_posix(UI_STANDARD_PATH)} missing: {', '.join(missing_markers)}"
        )

    package_path = root / "package.json"
    if not package_path.is_file():
        findings.append("FAIL UI_PACKAGE_MISSING package.json")
    else:
        try:
            package_data = json.loads(package_path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            findings.append(f"FAIL UI_PACKAGE_INVALID_JSON package.json {exc}")
        else:
            scripts = package_data.get("scripts")
            if not isinstance(scripts, dict):
                findings.append("FAIL UI_SCRIPTS_MISSING package.json scripts")
            else:
                for script_name in UI_REQUIRED_SCRIPTS:
                    script_value = scripts.get(script_name)
                    if not isinstance(script_value, str) or not script_value.strip():
                        findings.append(f"FAIL UI_SCRIPT_MISSING {script_name}")

    if project_has_ui_source(root):
        if not (root / UI_CONTRACT_SCRIPT_PATH).is_file():
            findings.append(f"FAIL UI_CONTRACT_SCRIPT_MISSING {to_posix(UI_CONTRACT_SCRIPT_PATH)}")
        if not any((root / "tests").glob("**/*.test.tsx")):
            findings.append("FAIL UI_COMPONENT_TEST_MISSING tests/**/*.test.tsx")
        if not any((root / "tests/e2e").glob("*.spec.ts")) and not any((root / "tests/e2e").glob("*.spec.tsx")):
            findings.append("FAIL UI_REAL_ENTRY_TEST_MISSING tests/e2e/*.spec.ts")

    if findings:
        return findings
    return ["OK UI_CONTROL_PASS UI standards, scripts, and interaction coverage controls are present"]


