def run(argv: list[str] | None = None) -> tuple[int, str]:
    parser = build_parser()
    args = parser.parse_args(argv)
    root = Path(args.root).resolve()

    if args.command == "verify":
        messages = verify(root)
    elif args.command == "gate":
        messages = gate(root, args.gate.lower())
    elif args.command == "snapshot":
        messages = snapshot(root, args.actor)
    elif args.command == "check-changes":
        messages = check_changes(root)
    elif args.command == "ui":
        messages = check_ui_process_control(root)
    else:
        parser.error("unknown command")

    code = 0 if all(message.startswith("OK ") for message in messages) else 1
    return code, "\n".join(messages) + "\n"


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Agent-Jarvis governance control CLI")
    subparsers = parser.add_subparsers(dest="command", required=True)

    verify_parser = subparsers.add_parser("verify", help="verify required governance files and baseline integrity")
    verify_parser.add_argument("--root", default=".", help="project root")

    gate_parser = subparsers.add_parser("gate", help="run a governance gate")
    gate_parser.add_argument("gate", choices=["g1", "g2", "g3", "g3.5", "g4"])
    gate_parser.add_argument("--root", default=".", help="project root")

    snapshot_parser = subparsers.add_parser("snapshot", help="write baseline hashes and append a ledger event")
    snapshot_parser.add_argument("--root", default=".", help="project root")
    snapshot_parser.add_argument("--actor", default="unknown", help="actor recorded in the ledger")

    changes_parser = subparsers.add_parser("check-changes", help="validate change records")
    changes_parser.add_argument("--root", default=".", help="project root")

    ui_parser = subparsers.add_parser("ui", help="validate UI process controls")
    ui_parser.add_argument("--root", default=".", help="project root")

    return parser


def verify(root: Path) -> list[str]:
    findings: list[str] = []
    findings.extend(check_required_structure(root))
    findings.extend(m for m in check_ui_process_control(root) if not m.startswith("OK "))
    findings.extend(check_baseline(root))
    findings.extend(check_ledger(root))

    if findings:
        return findings
    return ["OK VERIFY_PASS governance files and integrity checks passed"]


def gate(root: Path, gate_name: str) -> list[str]:
    structure_findings = check_required_structure(root)
    if structure_findings:
        return structure_findings

    if gate_name == "g1":
        return check_g1(root)
    if gate_name == "g2":
        g1 = check_g1(root)
        if not is_ok(g1):
            return ["FAIL G2_BLOCKED G1 must pass before G2"] + g1
        return check_g2(root)
    if gate_name == "g3":
        g2 = gate(root, "g2")
        if not is_ok(g2):
            return ["FAIL G3_BLOCKED G2 must pass before implementation validation"] + g2
        return check_g3(root)
    if gate_name == "g3.5":
        g3 = gate(root, "g3")
        if not is_ok(g3):
            return ["FAIL G3_5_BLOCKED G3 must pass before real-entry smoke validation"] + g3
        return check_g35(root)
    if gate_name == "g4":
        lower = gate(root, "g3.5")
        if not is_ok(lower):
            return ["FAIL G4_BLOCKED G3.5 must pass before release"] + lower
        return check_g4(root)
    return [f"FAIL UNKNOWN_GATE unsupported gate: {gate_name}"]


def snapshot(root: Path, actor: str) -> list[str]:
    findings = check_required_structure(root)
    if findings:
        return findings

    baseline = {
        "schema_version": 1,
        "created_at": now_utc(),
        "files": {rel_path: sha256_file(root / rel_path) for rel_path in discover_controlled_files(root)},
    }
    baseline_json = canonical_json(baseline)
    baseline["baseline_sha256"] = sha256_text(baseline_json)

    baseline_path = root / BASELINE_PATH
    baseline_path.parent.mkdir(parents=True, exist_ok=True)
    baseline_path.write_text(canonical_json(baseline) + "\n", encoding="utf-8")

    ledger_findings = append_ledger_event(
        root,
        {
            "action": "snapshot",
            "actor": actor,
            "payload_sha256": baseline["baseline_sha256"],
            "files": baseline["files"],
        },
    )
    if ledger_findings:
        return ledger_findings

    return [f"OK SNAPSHOT_WRITTEN {to_posix(BASELINE_PATH)}"]


def check_required_structure(root: Path) -> list[str]:
    findings: list[str] = []
    for rel_dir in PROJECT_DIRS:
        if not (root / rel_dir).is_dir():
            findings.append(f"FAIL MISSING_REQUIRED_DIR {rel_dir}")
    for rel_path in REQUIRED_FILES:
        if not (root / rel_path).is_file():
            findings.append(f"FAIL MISSING_REQUIRED_FILE {rel_path}")
    return findings


def check_baseline(root: Path) -> list[str]:
    baseline_path = root / BASELINE_PATH
    if not baseline_path.exists():
        return []

    try:
        baseline = json.loads(baseline_path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        return [f"FAIL BASELINE_INVALID_JSON {to_posix(BASELINE_PATH)} {exc}"]

    findings: list[str] = []
    files = baseline.get("files")
    if not isinstance(files, dict):
        return [f"FAIL BASELINE_INVALID_SCHEMA {to_posix(BASELINE_PATH)} missing files object"]

    for rel_path, expected_hash in files.items():
        path = root / rel_path
        if not path.exists():
            findings.append(f"FAIL BASELINE_FILE_MISSING {rel_path}")
            continue
        actual_hash = sha256_file(path)
        if actual_hash != expected_hash:
            findings.append(f"FAIL BASELINE_CHANGED {rel_path}")

    current_files = set(discover_controlled_files(root))
    baseline_files = set(files)
    for rel_path in sorted(current_files - baseline_files):
        findings.append(f"FAIL UNBASELINED_FILE {rel_path}")
    return findings


def discover_controlled_files(root: Path) -> list[str]:
    files: list[str] = []
    for path in root.rglob("*"):
        if not path.is_file():
            continue
        rel_path = path.relative_to(root)
        rel_parts = rel_path.parts
        if any(part in IGNORED_DIR_NAMES for part in rel_parts[:-1]):
            continue
        if any(part.startswith(IGNORED_DIR_PREFIXES) for part in rel_parts[:-1]):
            continue
        if rel_path.parts[:2] == ("project", ".governance"):
            continue
        if path.name in IGNORED_FILE_NAMES:
            continue
        if any(path.name.endswith(suffix) for suffix in IGNORED_SUFFIXES):
            continue
        files.append(to_posix(rel_path))
    return sorted(files)


def check_ledger(root: Path) -> list[str]:
    ledger_path = root / LEDGER_PATH
    if not ledger_path.exists():
        return []

    findings: list[str] = []
    previous_hash = "GENESIS"
    expected_seq = 1
    for line_number, line in enumerate(ledger_path.read_text(encoding="utf-8").splitlines(), start=1):
        if not line.strip():
            continue
        try:
            event = json.loads(line)
        except json.JSONDecodeError as exc:
            findings.append(f"FAIL LEDGER_INVALID_JSON line={line_number} {exc}")
            continue

        if event.get("seq") != expected_seq:
            findings.append(f"FAIL LEDGER_BAD_SEQUENCE line={line_number}")
        if event.get("prev_hash") != previous_hash:
            findings.append(f"FAIL LEDGER_BROKEN_CHAIN line={line_number}")

        recorded_hash = event.get("hash")
        event_without_hash = dict(event)
        event_without_hash.pop("hash", None)
        actual_hash = sha256_text(canonical_json(event_without_hash))
        if recorded_hash != actual_hash:
            findings.append(f"FAIL LEDGER_HASH_MISMATCH line={line_number}")

        previous_hash = str(recorded_hash)
        expected_seq += 1

    return findings


def check_g1(root: Path) -> list[str]:
    input_text = read_text(root / "project/00_input/需求输入.md")
    spec_text = read_text(root / "project/01_specification/产品需求说明书.md")
    findings: list[str] = []

    if not meaningful_input_exists(input_text):
        findings.append("FAIL G1_BLOCKED 原始需求输入缺失或尚未建立")
    if contains_placeholder_state(spec_text):
        findings.append("FAIL G1_BLOCKED 产品需求仍处于未确认状态，需要用户确认")
    if not approved_status_exists(spec_text):
        findings.append("FAIL G1_BLOCKED 产品需求说明书缺少 APPROVED 状态")
    if "用户确认" not in spec_text:
        findings.append("FAIL G1_BLOCKED 产品需求说明书缺少用户确认记录")
    if not approved_requirement_row_exists(spec_text):
        findings.append("FAIL G1_BLOCKED 产品需求说明书缺少带验收标准的已批准需求行")

    if findings:
        return findings
    return ["OK G1_PASS requirements baseline is approved and testable"]


def check_g2(root: Path) -> list[str]:
    architecture = read_text(root / "project/02_solution/架构设计说明书.md")
    modules = read_text(root / "project/03_modules/模块任务开发说明书.md")
    tests = read_text(root / "project/04_tests/测试说明书.md")
    findings: list[str] = []

    for rel_path, text in [
        ("project/02_solution/架构设计说明书.md", architecture),
        ("project/03_modules/模块任务开发说明书.md", modules),
        ("project/04_tests/测试说明书.md", tests),
    ]:
        if contains_placeholder_state(text):
            findings.append(f"FAIL G2_BLOCKED {rel_path} is still unapproved")

    requirement_ids = extract_ids(read_text(root / "project/01_specification/产品需求说明书.md"), "REQ")
    module_requirement_ids = extract_ids(modules, "REQ")
    test_requirement_ids = extract_ids(tests, "REQ")
    task_ids = extract_ids(modules, "TASK")
    test_ids = extract_ids(tests, "TEST")

    missing_module_coverage = sorted(requirement_ids - module_requirement_ids)
    missing_test_coverage = sorted(requirement_ids - test_requirement_ids)
    if missing_module_coverage:
        findings.append(f"FAIL G2_BLOCKED requirements missing module coverage: {', '.join(missing_module_coverage)}")
    if missing_test_coverage:
        findings.append(f"FAIL G2_BLOCKED requirements missing test coverage: {', '.join(missing_test_coverage)}")
    if not task_ids:
        findings.append("FAIL G2_BLOCKED no TASK ids defined")
    if not test_ids:
        findings.append("FAIL G2_BLOCKED no TEST ids defined")

    if findings:
        return findings
    return ["OK G2_PASS architecture, modules, and tests cover approved requirements"]


